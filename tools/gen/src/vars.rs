//! Generates every local settings file from `config.toml` and `config.local.toml`.

use std::{fs, io, path::Path};

use toml_edit::{DocumentMut, Item, value};

const HEADER: &str = "# Generated by `mask config` from config.toml and config.local.toml. Edit those instead.\n";

type Vars = Vec<(String, String)>;

pub fn generate(root: &Path) -> io::Result<()> {
    let config = read(&root.join("config.toml"))?;
    let local_path = root.join("config.local.toml");
    let mut local = if local_path.exists() { read(&local_path)? } else { DocumentMut::new() };

    // Read every setting before config.local.toml may be updated below.
    let (features, ports, settings) = {
        let get = |table: &str, key: &str| -> Option<Item> {
            local.get(table).and_then(|t| t.get(key)).or_else(|| config.get(table).and_then(|t| t.get(key))).cloned()
        };
        let string = |key: &str| get("voice", key).and_then(|item| item.as_str().map(str::to_owned)).unwrap_or_default();
        let integer = |key: &str, default: i64| get("ports", key).and_then(|item| item.as_integer()).unwrap_or(default);
        // Flags from both files; config.local.toml wins.
        let mut features: Vec<(String, bool)> = Vec::new();
        for document in [&config, &local] {
            for (name, flag) in document.get("features").and_then(Item::as_table_like).into_iter().flat_map(|t| t.iter()) {
                let Some(flag) = flag.as_bool() else { continue };
                match features.iter_mut().find(|(existing, _)| existing == name) {
                    Some(entry) => entry.1 = flag,
                    None => features.push((name.to_owned(), flag)),
                }
            }
        }
        let offset = integer("offset", 0);
        let port = |key: &str, default: i64| integer(key, default).saturating_add(offset);
        let ports = (port("client", 3000), port("server", 9000), port("voice", 9100));
        let settings = ["control_secret", "realtime_app_id", "realtime_app_token", "allowed_origins", "ice_servers"].map(string);
        (features, ports, settings)
    };
    let (client, server, voice) = ports;
    let [mut secret, app_id, app_token, allowed_origins, ice_servers] = settings;
    let voice_on = features.iter().any(|(name, flag)| name == "voice" && *flag);

    if voice_on && secret.is_empty() {
        secret = random_hex()?;
        local["voice"].or_insert(toml_edit::table())["control_secret"] = value(secret.as_str());
        fs::write(&local_path, local.to_string())?;
        println!("Stored a new voice control secret in config.local.toml");
    }

    let flags = |prefix: &str| -> Vars {
        features.iter().map(|(name, flag)| (format!("{prefix}FEATURE_{}", name.to_uppercase()), flag.to_string())).collect()
    };
    let pairs = |items: &[(&str, String)]| -> Vars { items.iter().map(|(k, v)| ((*k).to_owned(), v.clone())).collect() };

    let mut client_vars = pairs(&[("VITE_WS_ADDRESS", format!("ws://localhost:{server}")), ("CLIENT_PORT", client.to_string())]);
    client_vars.extend(flags("VITE_"));
    write(root, "client/.env.local", &client_vars)?;

    // The game server enables voice only when all of its voice settings are present.
    let mut native = pairs(&[("WS_ADDRESS", format!("0.0.0.0:{server}"))]);
    let mut serverless = pairs(&[("SERVER_DEV_PORT", server.to_string())]);
    native.extend(flags(""));
    serverless.extend(flags(""));
    if voice_on {
        native.extend(pairs(&[
            ("VOICE_CONTROL_SECRET", secret.clone()),
            ("VOICE_CONTROL_URL", format!("ws://127.0.0.1:{voice}/control")),
            ("VOICE_PUBLIC_URL", format!("ws://localhost:{voice}")),
        ]));
        serverless.extend(pairs(&[
            ("VOICE_CONTROL_SECRET", secret.clone()),
            // Separate wrangler dev processes can't upgrade WebSockets over a service binding.
            ("VOICE_CONTROL_URL", format!("ws://127.0.0.1:{voice}/control")),
            ("VOICE_PUBLIC_URL", format!("ws://localhost:{voice}")),
        ]));
    }
    write(root, "server/.env.local", &native)?;
    write(root, "deploy/server/.dev.vars", &serverless)?;

    let mut voice_vars = pairs(&[
        ("VOICE_DEV_PORT", voice.to_string()),
        ("VOICE_CONTROL_SECRET", secret),
        ("REALTIME_APP_ID", app_id.clone()),
        ("REALTIME_APP_TOKEN", app_token),
    ]);
    for (name, setting) in [("VOICE_ALLOWED_ORIGINS", allowed_origins), ("VOICE_ICE_SERVERS", ice_servers)] {
        if !setting.is_empty() { voice_vars.push((name.to_owned(), setting)); }
    }
    write(root, "deploy/voice/.dev.vars", &voice_vars)?;

    let summary: Vec<String> = features.iter().map(|(name, flag)| format!("{name}={flag}")).collect();
    println!("Ports: client {client}, server {server}, voice {voice}. Features: {}", summary.join(", "));
    if voice_on && app_id.is_empty() {
        println!("Voice audio needs voice.realtime_app_id and voice.realtime_app_token in config.local.toml (see voice/README.md).");
    }
    Ok(())
}

fn read(path: &Path) -> io::Result<DocumentMut> {
    fs::read_to_string(path)?
        .parse()
        .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, format!("{}: {error}", path.display())))
}

fn write(root: &Path, file: &str, vars: &[(String, String)]) -> io::Result<()> {
    let body: String = vars.iter().map(|(name, value)| format!("{name}={value}\n")).collect();
    fs::write(root.join(file), format!("{HEADER}{body}"))
}

fn random_hex() -> io::Result<String> {
    let mut bytes = [0u8; 32];
    getrandom::fill(&mut bytes).map_err(|error| io::Error::other(error.to_string()))?;
    Ok(bytes.iter().map(|byte| format!("{byte:02x}")).collect())
}
